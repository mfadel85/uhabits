 * Usage in AnalyticsActivity:
 * 
 * if (CloudConfig.load(this)) {
 *     // Configuration loaded successfully
 *     syncToCloudAnalytics()
 * } else {
 *     // Show setup instructions
 *     showCloudSetupDialog()
 * }
 */
